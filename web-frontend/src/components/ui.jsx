export const Avatar = ({ name, size = 36, online = false }) => {
  const initials = (name || '?').split(/\s+/).map((p) => p[0]).slice(0, 2).join('').toUpperCase()
  let h = 0
  for (const c of name || '') h = (h * 31 + c.charCodeAt(0)) % 360
  return (
    <span className={`avatar ${online ? 'online' : ''}`} style={{ width: size, height: size, fontSize: size * 0.38, background: `hsl(${h} 50% 42%)` }}>
      {initials}
    </span>
  )
}

export const StatusBadge = ({ status }) => <span className={`badge status-${status?.toLowerCase()}`}>{status?.toLowerCase()}</span>

export function ScoreRing({ score, size = 64 }) {
  const r = (size - 8) / 2
  const c = 2 * Math.PI * r
  const tone = score >= 70 ? 'var(--success)' : score >= 45 ? 'var(--warn)' : 'var(--danger)'
  return (
    <div className="score-ring" style={{ width: size, height: size }} title={`Compatibility ${score}/100`}>
      <svg width={size} height={size}>
        <circle cx={size / 2} cy={size / 2} r={r} stroke="var(--border)" strokeWidth="6" fill="none" />
        <circle cx={size / 2} cy={size / 2} r={r} stroke={tone} strokeWidth="6" fill="none"
          strokeDasharray={c} strokeDashoffset={c * (1 - score / 100)} strokeLinecap="round"
          transform={`rotate(-90 ${size / 2} ${size / 2})`} />
      </svg>
      <span style={{ fontSize: Math.max(10, Math.round(size * 0.26)) }}>{score}</span>
    </div>
  )
}

